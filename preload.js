const { contextBridge, ipcRenderer, webFrame } = require('electron');

contextBridge.exposeInMainWorld('api', {
  query: (gql, variables, lang, noCache) => ipcRenderer.invoke('wcl:query', gql, variables, lang, noCache),
  clearQueryCache: () => ipcRenderer.invoke('qcache:clear'),
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (cfg) => ipcRenderer.invoke('config:set', cfg),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  getMe: (code) => ipcRenderer.invoke('me:get', code),
  setMe: (code, name) => ipcRenderer.invoke('me:set', code, name),
  mapGet: (key) => ipcRenderer.invoke('map:get', key),
  mapPick: (key) => ipcRenderer.invoke('map:pick', key),
  mapCalib: (key, calib) => ipcRenderer.invoke('map:calib', key, calib),
  mapRemove: (key) => ipcRenderer.invoke('map:remove', key),
  mapSaveData: (key, dataUrl) => ipcRenderer.invoke('map:savedata', key, dataUrl),
  setZoom: (factor) => webFrame.setZoomFactor(Math.min(2, Math.max(0.5, Number(factor) || 1))),
  appInfo: () => ipcRenderer.invoke('app:info'),
  updateCheck: (source) => ipcRenderer.invoke('update:check', source),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  onUpdateProgress: (cb) => ipcRenderer.on('update:progress', (_e, f) => cb(f)),
  setPref: (key, value) => ipcRenderer.invoke('pref:set', key, value),
  clearIcons: () => ipcRenderer.invoke('icons:clear'),
  clearBossMaps: () => ipcRenderer.invoke('bossmaps:clear'),
  exportPng: (rect, name) => ipcRenderer.invoke('export:png', rect, name),
  exportText: (text, name, ext) => ipcRenderer.invoke('export:text', text, name, ext),
  takeDeepLink: () => ipcRenderer.invoke('deeplink:take'),
  onDeepLink: (cb) => ipcRenderer.on('deeplink', (_e, link) => cb(link)),
  rioGuilds: (term) => ipcRenderer.invoke('rio:guilds', term),
  rioRank: (o) => ipcRenderer.invoke('rio:rank', o),
  bnetStatus: () => ipcRenderer.invoke('bnet:status'),
  bnetSet: (o) => ipcRenderer.invoke('bnet:set', o),
  bnetLogin: () => ipcRenderer.invoke('bnet:login'),
  bnetLogout: () => ipcRenderer.invoke('bnet:logout'),
  bnetGuilds: (lang) => ipcRenderer.invoke('bnet:guilds', lang),
  bnetChar: (realm, name, lang, region) => ipcRenderer.invoke('bnet:char', realm, name, lang, region),
  rioChar: (region, realm, name) => ipcRenderer.invoke('rio:char', region, realm, name),
  bnetArmory: (realm, name, lang, region) => ipcRenderer.invoke('bnet:armory', realm, name, lang, region),
  bnetCrest: (realm, guild) => ipcRenderer.invoke('bnet:crest', realm, guild),
  bnetRoster: (realm, guild) => ipcRenderer.invoke('bnet:roster', realm, guild),
  talentMap: () => ipcRenderer.invoke('talents:map'),
  spellTip: (id, lang) => ipcRenderer.invoke('spell:tip', id, lang),
  clearSpells: () => ipcRenderer.invoke('spells:clear'),
  openDataFolder: () => ipcRenderer.invoke('app:opendata'),
  artGet: (key) => ipcRenderer.invoke('art:get', key),
  artSave: (key, dataUrl) => ipcRenderer.invoke('art:save', key, dataUrl),
});
